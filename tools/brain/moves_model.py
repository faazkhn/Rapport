OUT = REPO / "tests/brain"
MODELS = REPO / "server/patient-service/learned/models"


def labels() -> list[str]:
    """Rubric moves first (closed/open question included), then the intents not already named by a move."""
    moves = list(rubric.table()["moves"])
    return moves + [i["id"] for i in brain.intents() if i["id"] not in moves]


def _desc() -> dict:
    d = {i["id"]: i["description"] for i in brain.intents()}
    d.update({k: v for k, v in gen_lines.MOVES.items()})
    d.update({"closed_question": "asks a yes/no or one-word question", "open_question": "asks an open question that invites the patient to talk",
              "risk_question": "asks about suicide, self-harm, harming others or other risk", "repeat_question": "asks again what was already asked",
              "interrupt": "cuts the patient off or talks over them"})
    return d


SYSTEM = """You label what a doctor's line does in a psychiatric interview (outpatient or ward, India). Return every label that applies,
from the list only; most lines have one to three. A line can both ask something and be kind, rude, jargon-heavy or stacked.
Labels:
{labels}
Answer with the JSON only."""


def label_lines(client, lines: list[str]) -> list[list[str]]:
    labs, d = labels(), _desc()
    system = SYSTEM.format(labels="\n".join(f"- {x}: {d.get(x, x.replace('_', ' '))}" for x in labs if x not in ("repeat_question", "interrupt")))
    schema = {"type": "object", "additionalProperties": False, "required": ["labels"],
              "properties": {"labels": {"type": "array", "maxItems": 6, "items": {"type": "string", "enum": labs}}}}
    with ThreadPoolExecutor(2) as ex:
        res = list(ex.map(lambda x: ask_json(client, system, f"Doctor's line: {x}", schema, {"labels": []}, 200), lines))
    return [sorted(set(r["labels"])) if not r.get("judge_error") else None for r in res]


def log_lines() -> list[str]:
    out = []
    for p in sorted((REPO / "logs/twin").glob("*.jsonl")):
        lines = p.read_text(encoding="utf-8", errors="ignore").splitlines()
        if not any('"consent": true' in x for x in lines[:3]):  # a learner's session feeds training only with its consent flag
            continue
        for x in lines:
            try:
                e = json.loads(x)
            except ValueError:
                continue
            if e.get("type") == "snapshot" and e.get("doctor"):
                out.append(e["doctor"])
    return gen_lines.dedupe(out)


def cmd_label(client):
    gen = [json.loads(x) for x in (OUT / "gen_moves.jsonl").read_text().splitlines() if x.strip()]
    logs = gen_lines.drop_near_held_out(log_lines(), gen_lines.held_out_lines())
    rows = [{"line": g["line"], "source": f"gen:{g['kind']}", "target": g["target"]} for g in gen] + [{"line": x, "source": "log"} for x in logs]
    labs = label_lines(client, [r["line"] for r in rows])
    with (OUT / "train_labelled.jsonl").open("w") as f:
        for r, lab in zip(rows, labs):
            if lab is not None:
                f.write(json.dumps({**r, "labels": lab}, ensure_ascii=False) + "\n")
    agree = sum(r["target"] in lab for r, lab in zip(rows, labs) if lab is not None and "target" in r) / max(1, sum("target" in r for r in rows))
    print(f"labelled {sum(lab is not None for lab in labs)}/{len(rows)} lines ({len(logs)} from logs); judge agrees with the generator's "
          f"target on {agree:.1%}")


MANNER = ["greeting", "open_question", "closed_question", "empathy", "explain_reason", "apology", "offer_choice", "summarise", "judgement",
          "abuse", "threat", "premature_reassurance", "jargon", "stacked", "rushed", "jailbreak", "meta_ai", "off_topic"]
TOPIC_SYSTEM = """You label which clinical TOPIC a doctor's line asks about in a psychiatric interview (India). Return every topic the line
asks about (usually one; two if it asks two things; none for greetings, small talk or pure empathy). Topics:
{labels}
Answer with the JSON only."""
MANNER_SYSTEM = """You label HOW a doctor's line is said in a psychiatric interview (India), not what it asks about. Return every label
that fits (usually one or two). Labels:
{labels}
Answer with the JSON only."""


def _pass(client, lines, system, labs):
    d = _desc()
    system = system.format(labels="\n".join(f"- {x}: {d.get(x, x.replace('_', ' '))}" for x in labs))
    schema = {"type": "object", "additionalProperties": False, "required": ["labels"],
              "properties": {"labels": {"type": "array", "maxItems": 4, "items": {"type": "string", "enum": labs}}}}
    with ThreadPoolExecutor(2) as ex:
        res = list(ex.map(lambda x: ask_json(client, system, f"Doctor's line: {x}", schema, {"labels": []}, 150), lines))
    return [sorted(set(r["labels"])) if not r.get("judge_error") else None for r in res]


def topic_ids() -> list[str]:
    return [i["id"] for i in brain.intents() if i["id"] not in MANNER and i["id"] not in ("empathy_statement", "summarise", "check_understanding",
                                                                                        "greet_introduce", "interrupt", "judgmental_language",
                                                                                        "threaten_coerce", "offer_choice", "open_question",
                                                                                        "explain_confidentiality")]


def label2(client, rows: list[dict]) -> list[dict]:
    lines = [r["line"] for r in rows]
    topics, manner = _pass(client, lines, TOPIC_SYSTEM, topic_ids()), _pass(client, lines, MANNER_SYSTEM, MANNER)
    out = []
    for r, t, m in zip(rows, topics, manner):
        if t is None or m is None:
            continue
        tgt = r.get("target")
        if tgt and tgt in topic_ids() and tgt not in t:  # the generator wrote it for this topic, the judge disagrees: too noisy to train on
            continue
        if tgt and tgt in MANNER and tgt not in m:
            continue
        out.append({**r, "topics": t, "manner": m})
    return out


def cmd_label2(client):
    gen = [json.loads(x) for x in (OUT / "gen_moves.jsonl").read_text().splitlines() if x.strip()]
    logs = gen_lines.drop_near_held_out(log_lines(), gen_lines.held_out_lines())
    rows = [{"line": g["line"], "source": f"gen:{g['kind']}", "target": g["target"]} for g in gen] + [{"line": x, "source": "log"} for x in logs]
    train = label2(client, rows)
    (OUT / "train2.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in train))
    print(f"train2: kept {len(train)}/{len(rows)} lines (judge agrees with the generator's target)")
    gold = label2(client, gold_lines())
    (OUT / "gold2.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in gold))
    rng = np.random.default_rng(1)
    sample = sorted(rng.choice(len(gold), size=min(80, len(gold)), replace=False))
    (OUT / "gold2_review.md").write_text("# Hand check of the two-pass gold labels (80-line sample)\n\n| Line | Topics | Manner | Check |\n|---|---|---|---|\n"
                                         + "".join(f"| {gold[i]['line']} | {', '.join(gold[i]['topics'])} | {', '.join(gold[i]['manner'])} | |\n" for i in sample))
    print(f"gold2: {len(gold)} lines")


def gold_lines() -> list[dict]:
    rows = [{"line": r["line"], "source": f"paraphrase:{r['case']}"} for r in recall_bench.rows("test")]
    for p in sorted((REPO / "tests/llm-eval").glob("*/*.yaml")):
        rows += [{"line": t, "source": f"heldout:{p.parent.name}/{p.stem}"} for t in yaml.safe_load(p.read_text())["turns"]]
    return rows


def cmd_gold(client):
    rows = gold_lines()
    labs = label_lines(client, [r["line"] for r in rows])
    with (OUT / "gold.jsonl").open("w") as f:
        for r, lab in zip(rows, labs):
            if lab is not None:
                f.write(json.dumps({**r, "labels": lab}, ensure_ascii=False) + "\n")
    rng = np.random.default_rng(0)
    sample = rng.choice(len(rows), size=min(60, len(rows)), replace=False)
    (OUT / "gold_review.md").write_text("# Hand check of the judge's gold labels (60-line sample)\n\nMark each row ok / wrong (and the right "
                                        "labels). The classifier numbers are trusted only after this.\n\n| Line | Judge labels | Check |\n|---|---|---|\n"
                                        + "".join(f"| {rows[i]['line']} | {', '.join(labs[i] or ['(judge error)'])} | |\n" for i in sorted(sample)))
    print(f"gold: {sum(lab is not None for lab in labs)} lines")


def _xy(rows):
    labs = labels()
    X = twin.embed([r["line"] for r in rows])
    Y = np.array([[lab in r["labels"] for lab in labs] for r in rows], dtype=np.int8)
    return X, Y, labs


def cmd_train(model_id):
    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import cross_val_predict
    rows = [json.loads(x) for x in (OUT / "train_labelled.jsonl").read_text().splitlines() if x.strip()]
    X, Y, labs = _xy(rows)
    W, b, thr, n = np.zeros((len(labs), X.shape[1]), np.float32), np.zeros(len(labs), np.float32), np.full(len(labs), 0.5, np.float32), []
    for j, lab in enumerate(labs):
        y = Y[:, j]
        n.append(int(y.sum()))
        if y.sum() < 8:  # too few examples: never predicted (the lexical rule stays in charge of this label)
            thr[j] = 2.0
            continue
        clf = LogisticRegression(C=4.0, class_weight="balanced", max_iter=2000)
        p = cross_val_predict(clf, X, y, cv=5, method="predict_proba")[:, 1]
        cands = np.linspace(0.3, 0.9, 13)
        f1 = [2 * ((p >= t) & (y == 1)).sum() / max(1, (p >= t).sum() + y.sum()) for t in cands]
        thr[j] = cands[int(np.argmax(f1))]
        clf.fit(X, y)
        W[j], b[j] = clf.coef_[0], clf.intercept_[0]
    MODELS.mkdir(parents=True, exist_ok=True)
    np.savez(MODELS / f"{model_id}.npz", W=W, b=b, thr=thr, labels=np.array(labs), n=np.array(n), encoder=twin.RECALL_MODEL)
    print(f"trained {model_id} on {len(rows)} lines; labels with >= 8 examples: {sum(x >= 8 for x in n)}/{len(labs)}")


def f1(pred: list[set], gold: list[set], labs: list[str]) -> dict:
    tp = sum(len(p & g) for p, g in zip(pred, gold))
    fp = sum(len(p - g) for p, g in zip(pred, gold))
    fn = sum(len(g - p) for p, g in zip(pred, gold))
    per = {}
    for lab in labs:
        t = sum(lab in p and lab in g for p, g in zip(pred, gold))
        d = sum(lab in p for p in pred) + sum(lab in g for g in gold)
        if any(lab in g for g in gold):
            per[lab] = round(2 * t / max(1, d), 3)
    return {"micro_f1": round(2 * tp / max(1, 2 * tp + fp + fn), 3), "macro_f1": round(sum(per.values()) / max(1, len(per)), 3), "per_label": per}


def cmd_eval(model_id, client):
    import mind
    rows = [json.loads(x) for x in (OUT / "gold.jsonl").read_text().splitlines() if x.strip()]
    model = mind.move_model(model_id)
    gold = [set(r["labels"]) for r in rows]
    moves = set(rubric.table()["moves"]) - {"risk_question", "repeat_question", "interrupt"}  # context labels come from code, not text
    intents = {i["id"] for i in brain.intents()} - moves
    clf = [set(mind.classify(model, r["line"])) for r in rows]
    lex = [set(rubric.moves(r["line"])) & moves for r in rows]
    out = {"lines": len(rows),
           "moves_classifier": f1([p & moves for p in clf], [g & moves for g in gold], sorted(moves)),
           "moves_lexical": f1(lex, [g & moves for g in gold], sorted(moves)),
           "intents_classifier": f1([p & intents for p in clf], [g & intents for g in gold], sorted(intents))}
    if client is not None:  # the LLM tagger the debrief uses today (Gemma, slot 1)
        tagged = [set(brain.tag_intents(r["line"], None, client, "local")) & intents for r in rows]
        out["intents_llm_tagger"] = f1(tagged, [g & intents for g in gold], sorted(intents))
    (OUT / f"eval_{model_id}.json").write_text(json.dumps(out, indent=1))
    print(json.dumps({k: ({kk: vv for kk, vv in v.items() if kk != "per_label"} if isinstance(v, dict) else v) for k, v in out.items()}, indent=1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["label", "gold", "train", "eval", "label2"])
    ap.add_argument("--url", default="http://127.0.0.1:8081/v1", help="the judge (labels)")
    ap.add_argument("--tagger-url", default="http://127.0.0.1:8080/v1", help="the patient's llama-server (LLM tagger baseline in eval)")
    ap.add_argument("--id", default="moves-v1")
    a = ap.parse_args()
    if a.cmd == "train":
        return cmd_train(a.id)
    if a.cmd == "eval":
        return cmd_eval(a.id, OpenAI(base_url=a.tagger_url, api_key="local", timeout=120, max_retries=1))
    client = OpenAI(base_url=a.url, api_key="local", timeout=300, max_retries=1)
    {"label": cmd_label, "gold": cmd_gold, "label2": cmd_label2}[a.cmd](client)


if __name__ == "__main__":
    main()
