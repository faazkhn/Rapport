"""Builds docs/literature/matrix.md from the per-paper notes (one row per note). Run after editing any note."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] / "docs/literature"


def field(text, name):
    m = re.search(rf"\*\*{name}:\*\*\s*(.*?)(?:\s·\s\*\*|\n)", text)
    return m.group(1).strip() if m else ""


def row(p):
    t = p.read_text(encoding="utf-8")
    title = t.splitlines()[0].lstrip("# ").strip()
    verdict = (re.search(r"\*\*Verdict:\*\*\s*([a-z-]+)", t) or [None, "?"])[1]
    access = field(t, "Open access").lower()
    access = "full" if "full" in access and "not read" not in access else "not found" if access.startswith(("no", "not found")) else "abstract"
    year = (re.search(r"(19|20)\d\d", field(t, "Citation")) or [""])[0]
    cite = field(t, "Citation").split(".")[0]
    return (f"| [{p.stem}](notes/{p.name}) | {title} | {cite} | {year} | {access} | {field(t, 'Code licence') or '?'} "
            f"| {field(t, 'Informs')} | **{verdict}** |"), verdict, access


def main():
    rows = [row(p) for p in sorted((ROOT / "notes").glob("*.md"))]
    count = lambda i, v: sum(r[i] == v for r in rows)
    head = (f"# Literature matrix\n\nGenerated by `tools/literature/build_matrix.py` from `notes/` ({len(rows)} papers). "
            f"Read in full: {count(2, 'full')}; abstract only: {count(2, 'abstract')}; not found: {count(2, 'not found')}. "
            f"Verdicts: adopt {count(1, 'adopt')}, adapt {count(1, 'adapt')}, idea-only {count(1, 'idea-only')}, skip {count(1, 'skip')}.\n\n"
            "| Note | Paper | First author | Year | Read | Code licence | Informs | Verdict |\n|---|---|---|---|---|---|---|---|\n")
    (ROOT / "matrix.md").write_text(head + "\n".join(r[0] for r in rows) + "\n", encoding="utf-8")
    print(head.splitlines()[2])


if __name__ == "__main__":
    main()
